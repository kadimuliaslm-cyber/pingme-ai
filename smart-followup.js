let pingMeFollowUpTimer = null;

let pingMeFollowUpActive = false;

const PINGME_FOLLOWUP_DELAY = 2 * 60 * 1000;


// ------------------------------------------------------------
// Start / Reset the 2-minute timer
// ------------------------------------------------------------

function startPingMeFollowUpTimer() {
  stopPingMeFollowUpTimer();

  pingMeFollowUpActive = false;

  pingMeFollowUpTimer = setTimeout(() => {
    triggerPingMeFollowUp();
  }, PINGME_FOLLOWUP_DELAY);
}


// ------------------------------------------------------------
// Stop the timer
// ------------------------------------------------------------

function stopPingMeFollowUpTimer() {
  if (pingMeFollowUpTimer) {
    clearTimeout(pingMeFollowUpTimer);
    pingMeFollowUpTimer = null;
  }
}


// ------------------------------------------------------------
// Called after approximately 2 minutes of inactivity
// ------------------------------------------------------------

function triggerPingMeFollowUp() {
  if (pingMeFollowUpActive) {
    return;
  }

  pingMeFollowUpActive = true;

  /*
    Important:

    This function intentionally does not automatically invent
    a message yet.

    The actual conversation-aware follow-up message will be
    generated by the PingMe conversation system.
  */

  const event = new CustomEvent("pingme-followup-needed");

  window.dispatchEvent(event);
}


// ------------------------------------------------------------
// When the user starts typing again
// ------------------------------------------------------------

function pingMeUserActivity() {
  startPingMeFollowUpTimer();
}


// ------------------------------------------------------------
// Expose functions globally
// ------------------------------------------------------------

window.startPingMeFollowUpTimer =
  startPingMeFollowUpTimer;

window.stopPingMeFollowUpTimer =
  stopPingMeFollowUpTimer;

window.pingMeUserActivity =
  pingMeUserActivity;


// ------------------------------------------------------------
// Initial state
// ------------------------------------------------------------

console.log(
  "PingMe Smart Follow-up system loaded."
);
